create or replace function public.case_country_changed()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  i review_items;
begin
  if new.country_code is not distinct from old.country_code or new.country_code <> 'NG' then return new; end if;
  for i in select * from review_items where subject_id = new.id and kind = 'pricing' and stage = 'waiting_member' loop
    insert into case_events (review_item_id, actor_label, actor_role, what, why)
    values (i.id, 'System', 'Automatic', 'Member responded', 'Changed their profile country to Nigeria.');
    update review_items set stage = case when assigned_to is null then 'new' else 'in_review' end where id = i.id;
  end loop;
  return new;
end;
$$;
revoke all on function public.case_country_changed() from public, anon, authenticated;
