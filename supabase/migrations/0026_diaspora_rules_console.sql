create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_gender text := new.raw_user_meta_data ->> 'gender';
  v_country text := upper(coalesce(new.raw_user_meta_data ->> 'country_code', 'NG'));
begin
  if v_country !~ '^[A-Z]{2}$' then v_country := 'NG'; end if;

  insert into public.profiles (id, display_name, gender, country_code)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', 'New member'),
    v_gender,
    v_country
  );

  -- Everyone starts on Starter.
  insert into public.entitlements (profile_id, tier, source)
  values (new.id, 'starter', 'default');

  -- Women's launch offer: 30 days of FULL Premium Plus — or Diaspora Plus for
  -- women abroad (PRD §7) — granted automatically, no payment method. If the
  -- country is set later, womens_offer_follows_track (0025) switches it.
  if v_gender = 'woman' then
    insert into public.entitlements (profile_id, tier, source, ends_at)
    values (new.id, case when v_country = 'NG' then 'premium_plus'::tier else 'diaspora_plus'::tier end,
            'womens_launch_offer', now() + interval '30 days');
  end if;

  return new;
end;
$$;

