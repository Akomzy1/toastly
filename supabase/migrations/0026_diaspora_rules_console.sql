-- The member responds: a fresh selfie passes, or they move to a Diaspora
-- plan, or they change their profile country to Nigeria.
create or replace function public.reverification_passed()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_n integer;
  i review_items;
begin
  if new.product = 'smartselfie' and new.passed is true and old.passed is distinct from true then
    delete from reverification_requests where profile_id = new.profile_id and requested_at <= new.created_at;
    get diagnostics v_n = row_count;
    if v_n > 0 then
      for i in select * from review_items where subject_id = new.profile_id and stage = 'waiting_member' loop
        insert into case_events (review_item_id, actor_label, actor_role, what, why)
        values (i.id, 'System', 'Automatic', 'Member responded', 'Selfie liveness passed.');
        update review_items set stage = case when assigned_to is null then 'new' else 'in_review' end where id = i.id;
      end loop;
    end if;
  end if;
  return new;
end;
$$;

create or replace function public.case_member_switched()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  i review_items;
begin
  if new.tier not in ('diaspora', 'diaspora_plus') or new.source <> 'subscription' then return new; end if;
  for i in select * from review_items where subject_id = new.profile_id and kind = 'pricing' and stage = 'waiting_member' loop
    insert into case_events (review_item_id, actor_label, actor_role, what, why)
    values (i.id, 'System', 'Automatic', 'Member responded', 'Moved to a Diaspora plan.'),
           (i.id, 'System', 'Automatic', 'Closed', 'Plan change completed.');
    update review_items set stage = 'decided', status = 'closed', decision = 'member_switched', decided_at = now() where id = i.id;
  end loop;
  return new;
end;
$$;
